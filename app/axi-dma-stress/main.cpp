struct BandwidthAnalysis
{
    double actual_data_mbps;
    double actual_interrupt_mbps;

    void PrintAnalysis() const
    {
        SPDLOG_INFO("=== BANDWIDTH ANALYSIS ===");
        SPDLOG_INFO("Actual Data Bandwidth: {:.2f} MB/s ({:.2f} Mbps)", actual_data_mbps, actual_data_mbps * 8);
        SPDLOG_INFO("Interrupt-based Bandwidth: {:.2f} MB/s ({:.2f} Mbps)", actual_interrupt_mbps, actual_interrupt_mbps * 8);
    }
};

BandwidthAnalysis CalculateBandwidth(uint32_t frame_size,
                                     uint32_t received_interrupts,
                                     uint32_t total_frames,
                                     double test_duration_seconds)
{

    BandwidthAnalysis analysis{};

    std::uint64_t total_data_bytes = static_cast<std::uint64_t>(total_frames) * frame_size;
    analysis.actual_data_mbps = total_data_bytes / (test_duration_seconds * 1024 * 1024);

    std::uint64_t interrupt_data_bytes = static_cast<std::uint64_t>(received_interrupts) * frame_size;
    analysis.actual_interrupt_mbps = interrupt_data_bytes / (test_duration_seconds * 1024 * 1024);

    return analysis;
}

void TestAxiDmaSimpleSingleChannel()
{
    Dma::AxiDma::Config dma_config{
        .HasStsCntrlStrm = false,
        .HasMm2sDRE = false,
        .Mm2SDataWidth = 0,
        .HasS2mmDRE = false,
        .S2MmDataWidth = 32,
        .Mm2SNumChannels = 0,
        .S2MmNumChannels = 1,
        .Mm2SBurstSize = 0,
        .S2MmBurstSize = 256,
        .MicroDmaChannel = false,
        .AddressWidth = 32,
        .BufferLengthRegister = 26};

    static constexpr uint32_t TEST_SAMPLE_COUNT = 10u;
    static constexpr uint32_t TEST_FRAME_INTERVAL_US = 10u;

    std::vector<std::vector<int>> results;

    AxiDataGen dataGen("data-generator-dma-simple");
    dataGen.SetConfig(TEST_SAMPLE_COUNT, TEST_FRAME_INTERVAL_US);

    Dma::UDmaBuffer dmaBuffer(Dma::UDmaBuffer::CachePolicy::Cached);
    uint32_t frame_size = TEST_SAMPLE_COUNT * sizeof(uint32_t);

    Dma::UDmaBufferAllocate::UdmaBufConfig buffer_config = {
        .buffer_vec = {{0, frame_size}}};

    if (!dmaBuffer.CreateBuffer(buffer_config))
    {
        SPDLOG_ERROR("Failed to create DMA buffers");
        return;
    }

    Dma::AxiDma axiDma("axi-dma-simple", dma_config);
    axiDma.InitializeSimpleModeConfig(&dmaBuffer, "udmabuf0", "");

    std::atomic<bool> test_running{true};
    std::atomic<int> interrupt_count{0};

    size_t frame_size_words = frame_size / sizeof(std::uint32_t);

    axiDma.AttachInterruptRxHandler([&, frame_size_words]()
                                    {
        if (!test_running.load())
         {
             return;
         }
    
        std::byte *data_ptr = dmaBuffer.BufferPtr("udmabuf0");
        std::uint32_t *frame_data = reinterpret_cast<uint32_t *>(data_ptr);
        
        std::vector<int> current_frame;
        current_frame.reserve(frame_size_words);
        
        for (size_t i = 0; i < frame_size_words; ++i) {
            current_frame.push_back(static_cast<int>(frame_data[i]));
        }
        
        results.push_back(std::move(current_frame));
        
        interrupt_count++;
        
        axiDma.XAxiDmaRxSimpleTransfer(frame_size); }, false);

    SPDLOG_INFO("Starting 10-second test with single frame transfers...");

    axiDma.XAxiDmaRxSimpleTransfer(frame_size);
    dataGen.Start();

    std::this_thread::sleep_for(std::chrono::seconds(10));

    SPDLOG_INFO("IRQ Count generated by DMA: {}", dataGen.GetInterruptCount());
    SPDLOG_INFO("Backpressure Count generated by DMA: {}", dataGen.GetBackPressureCount());
    SPDLOG_INFO("Average DMA IRQ interval: {:.3f} ms", dataGen.GetIntervalResultMs());

    test_running.store(false);
    axiDma.DetachRxInterruptHandler();
    axiDma.Stop();
    dataGen.Stop();

    SPDLOG_INFO("Test completed. Total frames captured: {}", results.size());
    for (const auto &frame : results)
    {
        int frame_number = frame[0];
        for (int i = 1; i < frame.size(); ++i)
        {
            if (frame[i] != frame_number + i)
            {
                SPDLOG_ERROR("Data mismatch detected in frame {}: expected {}, got {}", frame_number, frame_number + i, frame[i]);
            }
        }
    }
    SPDLOG_INFO("Data integrity verified for all captured frames.");
}

void TestAxiDmaCyclicSingleChannel(std::uint32_t sample_count_in_frame, std::uint32_t frame_interval_us, std::uint32_t bd_count, std::uint32_t test_duration_seconds = 5, Dma::UDmaBuffer::CachePolicy cache_policy = Dma::UDmaBuffer::CachePolicy::NonCached, std::uint32_t read_sample_count = 11)
{
    Dma::AxiDma::Config dma_config{
        .HasStsCntrlStrm = false,
        .HasMm2s = false,
        .HasMm2sDRE = false,
        .Mm2SDataWidth = 0,
        .HasS2mm = false,
        .HasS2mmDRE = false,
        .S2MmDataWidth = 32,
        .HasScatterGather = true,
        .Mm2SNumChannels = 0,
        .S2MmNumChannels = 1,
        .Mm2SBurstSize = 0,
        .S2MmBurstSize = 256,
        .MicroDmaChannel = false,
        .AddressWidth = 32,
        .BufferLengthRegister = 26};

    AxiDataGen dataGen("data-generator-dma-sg");
    dataGen.SetConfig(sample_count_in_frame, frame_interval_us);

    Dma::UDmaBuffer dmaBuffer(cache_policy);
    uint32_t frame_size = sample_count_in_frame * sizeof(uint32_t);

    Dma::UDmaBufferAllocate::UdmaBufConfig buffer_config{
        .buffer_vec = {
            {0, frame_size * bd_count}, // for streamdata bd count * one frame size udmabuf0
            {1, 64 * bd_count}          // sizeof bd * bd_count for BD descriptors udmabuf1
        }};

    if (!dmaBuffer.CreateBuffer(buffer_config))
    {
        SPDLOG_ERROR("Failed to create DMA buffers");
        return;
    }

    Dma::AxiDma axiDma("axi-dma-sg", dma_config);
    axiDma.InitializeCyclicModeConfig(&dmaBuffer, "udmabuf0", "udmabuf1", "", "");

    std::atomic<bool> test_running{true};
    std::atomic<int> interrupt_count{0};
    std::atomic<int> correct_frames{0};
    std::atomic<int> incorrect_frames{0};

    axiDma.AttachInterruptRxHandler([&]()
                                    {
        if (!test_running.load())
        {
            return;
        }

        std::uint32_t* buffer_start = axiDma.GetCurrentBufferAddress();
        std::uint32_t frame_id = buffer_start[0];

        bool frame_valid = true;

        for (std::uint32_t i = 0; i < read_sample_count; ++i)
        {
            std::uint32_t expected_value = frame_id + i;            
            if (buffer_start[i] != expected_value)
            {
                frame_valid = false;
            }
        }

        if (frame_valid) {
            correct_frames++;
        } else {
            incorrect_frames++;
        }
  
        interrupt_count++; }, false);

    axiDma.XAxiDmaRxCyclicTransfer();
    dataGen.Start();

    auto start_time = std::chrono::high_resolution_clock::now();
    std::this_thread::sleep_for(std::chrono::seconds(test_duration_seconds));

    auto end_time = std::chrono::high_resolution_clock::now();
    double test_duration = std::chrono::duration<double>(end_time - start_time).count();
    SPDLOG_INFO("Test ran for {:.3f} seconds", test_duration);

    SPDLOG_INFO("IRQ Count generated by DMA: {}", dataGen.GetInterruptCount());
    SPDLOG_INFO("IRQ Count received by handler: {}", interrupt_count.load());
    SPDLOG_INFO("Average DMA IRQ interval: {:.3f} ms", dataGen.GetIntervalResultMs());
    SPDLOG_INFO("Backpressure Count generated by DMA: {}", dataGen.GetBackPressureCount());

    test_running.store(false);
    axiDma.DetachRxInterruptHandler();
    axiDma.Stop();
    dataGen.Stop();

    auto bandwidth = CalculateBandwidth(
        frame_size,
        interrupt_count.load(),
        correct_frames.load() + incorrect_frames.load(),
        test_duration);
    bandwidth.PrintAnalysis();

    double frame_rate = interrupt_count.load() / test_duration;
    double expected_frame_rate = 1000000.0 / frame_interval_us;

    SPDLOG_INFO("=== PERFORMANCE METRICS ===");
    SPDLOG_INFO("Expected frame rate: {:.2f} Hz", expected_frame_rate);
    SPDLOG_INFO("Actual frame rate: {:.2f} Hz", frame_rate);
    SPDLOG_INFO("Average latency per frame: {:.3f} ms", 1000.0 / frame_rate);
    SPDLOG_INFO("=== DATA INTEGRITY RESULTS ===");
    SPDLOG_INFO("Correct frames: {}", correct_frames.load());
    SPDLOG_INFO("Incorrect frames: {}", incorrect_frames.load());
}

void TestAxiDmaCyclicSingleChannelPolling(std::uint32_t sample_count_in_frame, std::uint32_t frame_interval_us, std::uint32_t bd_count, std::uint32_t test_duration_seconds = 5, Dma::UDmaBuffer::CachePolicy cache_policy = Dma::UDmaBuffer::CachePolicy::NonCached, std::uint32_t read_sample_count = 11)
{
    SPDLOG_INFO("Starting AxiDma Cyclic Single Channel Polling Test...");
    Dma::AxiDma::Config dma_config{
        .HasStsCntrlStrm = false,
        .HasMm2s = false,
        .HasMm2sDRE = false,
        .Mm2SDataWidth = 0,
        .HasS2mm = false,
        .HasS2mmDRE = false,
        .S2MmDataWidth = 32,
        .HasScatterGather = true,
        .Mm2SNumChannels = 0,
        .S2MmNumChannels = 1,
        .Mm2SBurstSize = 0,
        .S2MmBurstSize = 256,
        .MicroDmaChannel = false,
        .AddressWidth = 32,
        .BufferLengthRegister = 26};

    std::vector<std::vector<int>> results;

    AxiDataGen dataGen("data-generator-dma-sg");
    dataGen.SetConfig(sample_count_in_frame, frame_interval_us);

    Dma::UDmaBuffer dmaBuffer(cache_policy);
    uint32_t frame_size = sample_count_in_frame * sizeof(uint32_t);

    Dma::UDmaBufferAllocate::UdmaBufConfig buffer_config{
        .buffer_vec = {
            {0, frame_size * bd_count}, // for streamdata bd count * one frame size udmabuf0
            {1, 64 * bd_count}          // sizeof bd * bd_count for BD descriptors udmabuf1
        }};

    if (!dmaBuffer.CreateBuffer(buffer_config))
    {
        SPDLOG_ERROR("Failed to create DMA buffers");
        return;
    }

    Dma::AxiDma axiDma("axi-dma-sg", dma_config);
    axiDma.InitializeCyclicModeConfig(&dmaBuffer, "udmabuf0", "udmabuf1", "", "");

    std::atomic<bool> test_running{true};
    std::atomic<int> interrupt_count{0};
    std::atomic<int> correct_frames{0};
    std::atomic<int> incorrect_frames{0};

    auto start_time = std::chrono::steady_clock::now();
    auto end_time = start_time;
    double elapsed_sec = 0.0;

    auto test_duration = std::chrono::duration<double>(test_duration_seconds);

    axiDma.XAxiDmaRxCyclicTransfer();
    dataGen.Start();

    while (test_running.load() && (elapsed_sec < test_duration.count()))
    {
        auto irq_status = axiDma.ReadInterruptStatusRx();
        if (irq_status)
        {
            axiDma.ClearInterruptsRx();
            axiDma.ProcessCompletedBDsRx();
            interrupt_count++;

            std::uint32_t *buffer_start = axiDma.GetCurrentBufferAddress();
            std::uint32_t frame_id = buffer_start[0];

            bool frame_valid = true;

            for (std::uint32_t i = 0; i < read_sample_count; ++i)
            {
                std::uint32_t expected_value = frame_id + i;
                if (buffer_start[i] != expected_value)
                {
                    frame_valid = false;
                }
            }

            if (frame_valid)
            {
                correct_frames++;
            }
            else
            {
                incorrect_frames++;
            }
        }

        end_time = std::chrono::steady_clock::now();
        elapsed_sec = std::chrono::duration<double>(end_time - start_time).count();
    }

    test_running.store(false);
    axiDma.Stop();
    dataGen.Stop();

    SPDLOG_INFO("Test ran for {:.3f} seconds", elapsed_sec);
    SPDLOG_INFO("IRQ Count generated by DMA: {}", dataGen.GetInterruptCount());
    SPDLOG_INFO("IRQ Count received by handler: {}", interrupt_count.load());
    SPDLOG_INFO("Average DMA IRQ interval: {:.3f} ms", dataGen.GetIntervalResultMs());
    SPDLOG_INFO("Backpressure Count generated by DMA: {}", dataGen.GetBackPressureCount());

    auto bandwidth = CalculateBandwidth(
        frame_size,
        interrupt_count.load(),
        correct_frames.load() + incorrect_frames.load(),
        elapsed_sec);
    bandwidth.PrintAnalysis();

    double frame_rate = interrupt_count.load() / elapsed_sec;
    double expected_frame_rate = 1000000.0 / frame_interval_us;

    SPDLOG_INFO("=== PERFORMANCE METRICS ===");
    SPDLOG_INFO("Expected frame rate: {:.2f} Hz", expected_frame_rate);
    SPDLOG_INFO("Actual frame rate: {:.2f} Hz", frame_rate);
    SPDLOG_INFO("Average latency per frame: {:.3f} ms", 1000.0 / frame_rate);
    SPDLOG_INFO("=== DATA INTEGRITY RESULTS ===");
    SPDLOG_INFO("Correct frames: {}", correct_frames.load());
    SPDLOG_INFO("Incorrect frames: {}", incorrect_frames.load());
}

int main(int argc, char *argv[])
{
    spdlog::set_level(spdlog::level::debug);
    spdlog::set_pattern("[%^%l%$] %v");

    if (argc < 7)
    {
        SPDLOG_ERROR("Usage: {} <samples_per_frame> <frame_interval_us> <bd_count> <test_duration_seconds> <cache_policy> <read_sample_count>", argv[0]);
        SPDLOG_ERROR("  samples_per_frame: Number of samples in each frame");
        SPDLOG_ERROR("  frame_interval_us: Interval between frames in microseconds");
        SPDLOG_ERROR("  bd_count: Number of buffer descriptors");
        SPDLOG_ERROR("  test_duration_seconds: Duration of test in seconds");
        SPDLOG_ERROR("  cache_policy: 'cached' or 'noncached'");
        SPDLOG_ERROR("  read_sample_count: Number of samples to read/validate per frame (must be <= samples_per_frame)");
        return -1;
    }

    std::uint32_t sample_count_in_frame = std::stoi(argv[1]);
    std::uint32_t frame_interval_us = std::stoi(argv[2]);
    std::uint32_t bd_count = std::stoi(argv[3]);
    std::uint32_t test_duration_seconds = std::stoi(argv[4]);
    std::string cache_policy_str = argv[5];
    std::uint32_t read_sample_count = std::stoi(argv[6]);

    Dma::UDmaBuffer::CachePolicy cache_policy;
    if (cache_policy_str == "cached")
    {
        cache_policy = Dma::UDmaBuffer::CachePolicy::Cached;
        SPDLOG_INFO("Using cached memory policy");
    }
    else if (cache_policy_str == "noncached")
    {
        cache_policy = Dma::UDmaBuffer::CachePolicy::NonCached;
        SPDLOG_INFO("Using non-cached memory policy");
    }
    else
    {
        SPDLOG_ERROR("Invalid cache policy '{}'. Use 'cached' or 'noncached'", cache_policy_str);
        return -1;
    }

    if (read_sample_count == 0)
    {
        SPDLOG_ERROR("read_sample_count must be greater than 0");
        return -1;
    }

    if (read_sample_count > sample_count_in_frame)
    {
        SPDLOG_ERROR("read_sample_count ({}) cannot be greater than samples_per_frame ({})",
                     read_sample_count, sample_count_in_frame);
        return -1;
    }

    try
    {
        // TestAxiDmaSimpleSingleChannel();
        // TestAxiDmaCyclicSingleChannel(sample_count_in_frame, frame_interval_us, bd_count, test_duration_seconds, cache_policy, read_sample_count);
        TestAxiDmaCyclicSingleChannelPolling(sample_count_in_frame, frame_interval_us, bd_count, test_duration_seconds, cache_policy, read_sample_count);
    }
    catch (const std::exception &e)
    {
        SPDLOG_ERROR("Error: {}", e.what());
    }

    return 0;
}
